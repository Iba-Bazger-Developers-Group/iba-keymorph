using System.Globalization;
using System.Text;
using IbaKeyMorph.Core;
using Xunit;

namespace IbaKeyMorph.Core.Tests;

public class TextConverterTests
{
    private static TableLayout En => BuiltInLayouts.English;

    private static TableLayout Ru => BuiltInLayouts.Russian;

    [Fact]
    public void ConvertsWholePhrases()
    {
        Assert.Equal("Привет, как дела?", TextConverter.Convert("Ghbdtn? rfr ltkf&", En, Ru));
        Assert.Equal("Hello, world!", TextConverter.Convert("Руддщб цщкдв!", Ru, En));
    }

    [Fact]
    public void LeavesUnknownCharactersAlone()
    {
        Assert.Equal("2024 — год", TextConverter.Convert("2024 — ujl", En, Ru));
    }

    [Fact]
    public void PicksDirectionFromTheText()
    {
        var layouts = new IKeyboardLayout[] { En, Ru };

        var toRussian = TextConverter.PickConversion("Ghbdtn? rfr ltkf&", layouts);
        var toEnglish = TextConverter.PickConversion("Руддщб цщкдв!", layouts);

        Assert.Equal((En, Ru), (toRussian!.Value.From, toRussian.Value.To));
        Assert.Equal((Ru, En), (toEnglish!.Value.From, toEnglish.Value.To));
        Assert.Null(TextConverter.PickConversion("123 !?", layouts));
    }
}

public class DoubleTapDetectorTests
{
    private const int Shift = 1;
    private const int Other = 2;

    [Fact]
    public void DetectsTwoQuickTaps()
    {
        var d = new DoubleTapDetector();
        d.KeyDown(Shift, 0);
        Assert.False(d.KeyUp(Shift, 80));
        d.KeyDown(Shift, 200);
        Assert.True(d.KeyUp(Shift, 260));
    }

    [Fact]
    public void IgnoresSlowTapsLongHoldsAndInterruptions()
    {
        var slow = new DoubleTapDetector();
        slow.KeyDown(Shift, 0);
        slow.KeyUp(Shift, 50);
        slow.KeyDown(Shift, 1000);
        Assert.False(slow.KeyUp(Shift, 1050));

        var hold = new DoubleTapDetector();
        hold.KeyDown(Shift, 0);
        hold.KeyUp(Shift, 50);
        hold.KeyDown(Shift, 100);
        Assert.False(hold.KeyUp(Shift, 900));

        var interrupted = new DoubleTapDetector();
        interrupted.KeyDown(Shift, 0);
        interrupted.KeyUp(Shift, 50);
        interrupted.Reset();
        interrupted.KeyDown(Shift, 100);
        Assert.False(interrupted.KeyUp(Shift, 150));
    }

    [Fact]
    public void DifferentKeysDoNotCombine()
    {
        var d = new DoubleTapDetector();
        d.KeyDown(Shift, 0);
        d.KeyUp(Shift, 50);
        d.KeyDown(Other, 100);
        Assert.False(d.KeyUp(Other, 150));
    }

    [Fact]
    public void AutoRepeatDoesNotCount()
    {
        var d = new DoubleTapDetector();
        d.KeyDown(Shift, 0);
        d.KeyDown(Shift, 30);
        d.KeyDown(Shift, 60);
        Assert.False(d.KeyUp(Shift, 90));
    }
}

public class LanguageModelTests
{
    [Fact]
    public void NormalisesYoAndCase()
    {
        Assert.Equal("еще", LanguageModel.Normalize("ЕЩЁ"));
        Assert.True(Languages.Russian.Contains(LanguageModel.Normalize("ЕЩЁ")));
    }

    [Fact]
    public void WellFormedness()
    {
        Assert.True(Languages.English.IsWellFormed("don't"));
        Assert.True(Languages.Russian.IsWellFormed("кто-то"));
        Assert.False(Languages.Russian.IsWellFormed("-то"));
        Assert.False(Languages.English.IsWellFormed("a,b"));
        Assert.False(Languages.English.IsWellFormed("привет"));
    }

    [Fact]
    public void RealWordsScoreHigherThanLayoutGibberish()
    {
        Assert.True(Languages.English.Score("keyboard") > Languages.English.Score("ghbdtn") + 1);
        Assert.True(Languages.Russian.Score("клавиатура") > Languages.Russian.Score("руддщ") + 1);
    }

    [Fact]
    public void ParsesCommentsAndWhitespace()
    {
        var words = Languages.ParseWordList("# header\nfoo bar # tail\n\n  baz\r\n").ToList();
        Assert.Equal(new[] { "foo", "bar", "baz" }, words);
    }

    /// <summary>
    /// data/tests/golden-scores.tsv pins the model output so the Swift port can be checked against it.
    /// Run with IBA_REGENERATE_GOLDEN=1 after changing word lists or the model.
    /// </summary>
    [Fact]
    public void GoldenScoresMatch()
    {
        var samples = new (string Language, string Word)[]
        {
            ("en", "hello"), ("en", "keyboard"), ("en", "ghbdtn"), ("en", "don't"), ("en", "x"),
            ("en", "well-known"), ("en", "zzzz"), ("en", "algorithm"), ("en", "rfr"),
            ("ru", "привет"), ("ru", "клавиатура"), ("ru", "руддщ"), ("ru", "кто-то"), ("ru", "я"),
            ("ru", "щщщщ"), ("ru", "алгоритм"), ("ru", "ерк"), ("ru", "еще"),
        };

        var expected = new StringBuilder("# language\tword\tscore\tin-dictionary (generated by C# tests)\n");
        foreach (var (language, word) in samples)
        {
            var model = Languages.ForCode(language)!;
            expected.Append(language).Append('\t').Append(word).Append('\t')
                .Append(model.Score(word).ToString("F9", CultureInfo.InvariantCulture)).Append('\t')
                .Append(model.Contains(word) ? "1" : "0").Append('\n');
        }

        var path = Path.Combine(TestData.SourceDataDirectory, "tests", "golden-scores.tsv");
        if (Environment.GetEnvironmentVariable("IBA_REGENERATE_GOLDEN") == "1")
        {
            File.WriteAllText(path, expected.ToString());
        }

        Assert.Equal(expected.ToString(), File.ReadAllText(path).Replace("\r\n", "\n"));
    }
}
